#!/usr/bin/env python3
"""把数据库 dump 成可 diff 的 SQL 文本，供 git 备份（T5，2026-10-19）。

## 为什么只 dump 版本库，不 dump 索引库

| 库 | 能否重建 | 要不要备份 |
|---|---|---|
| `index.sqlite3` | **不能**（2026-10-21 订正）。切「库为源」之后它就是唯一本体，md 是**它的快照**、不是它的源 —— 从 md 重建会丢掉「已入库、md 未导出」的行 | git 里不 dump 二进制：13.78 MB × 每次提交，73 次就约 1 GB，且 diff 里看不见改了什么。本体备份走 `脚本/backup_db.py`（本机二进制快照，最近 7 天 + 每月首日） |
| `versions.sqlite3` | **不能** —— 历史只发生一次，删了就没了 | **必须**。当前约 1.2 MB，dump 成文本进 git |

> **历史注记**：本表第一行原来写的是「`index.sqlite3` 能 —— 一条命令从 md 全量重建（`memory_web.py --rebuild-only`），所以不要备份」。那句在 **md 为源** 时代成立，2026-10-20 反转事实源之后就反了 —— `auto_push.sh`（10-19 P0-3）早已改成「index 是唯一本体」。留着旧口径的代价是：下一个读到它的人会以为 index 可再生，于是不做备份。

「备份」这件事的本质是**备份不可再生的东西**。把可重建的索引也塞进 git，等于用
仓库体积换一个本来就有的能力。

## 为什么不直接 commit .sqlite3

二进制文件在 git 里存的是整份快照：改一条版本记录，git 就多存一整个 24 KB 的
新 blob，而且** diff 里看不见改了什么**。文本 SQL 则是逐行的：一次改动几行，
`git log -p` 直接能读。

## 行序必须稳定

`sqlite3.iterdump()` 不保证行序。行序一变，dump 出来的文件就整篇「都变了」，
git diff 变成噪音，备份就失去可读性。所以本脚本**自己拼 INSERT 并按主键排序**，
保证同样的数据永远 dump 出同样的文本。

用法：
    python 脚本/db_dump.py              # dump 版本库（默认，这是每日备份该做的）
    python 脚本/db_dump.py --check      # 只报差异，不写
    python 脚本/db_dump.py --index      # 连索引库一起 dump（临时取证用，日常别开）
"""

from __future__ import annotations

import argparse
import os
import sqlite3
import sys
from pathlib import Path

try:
    from _usage import autotrack

    autotrack(__file__)
except Exception:  # noqa: BLE001
    pass

VAULT = Path(__file__).resolve().parent.parent
OUT_DIR = VAULT / "备份归档" / "db-dump"
sys.path.insert(0, str(VAULT))
import db_paths  # noqa: E402  数据库位置唯一入口（2026-10-19 收口到「数据库/」）

# 每张表：表名 → (建表 SQL, 排序列)。排序列决定 dump 的稳定顺序。
TABLES = {
    "versions": (
        db_paths.resolve("versions.sqlite3"),
        [
            (
                "note_versions",
                """CREATE TABLE IF NOT EXISTS note_versions (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    title       TEXT    NOT NULL,
    rel_path    TEXT    NOT NULL,
    version     INTEGER NOT NULL,
    recorded_at TEXT    NOT NULL,
    chars       INTEGER NOT NULL,
    source      TEXT,
    note        TEXT,
    body_md     TEXT    NOT NULL,
    UNIQUE(title, version)
);""",
                "title, version",
            )
        ],
    ),
    "index": (
        db_paths.resolve("index.sqlite3"),
        [
            ("notes", None, "rel_path"),
            ("links", None, "src, dst"),
            ("meta", None, "k"),
        ],
    ),
}


def _sql_literal(v: object) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v).replace("'", "''")
    return "'" + s + "'"


def dump_db(db_path: Path, specs: list[tuple[str, str | None, str]], header: str) -> str:
    """按稳定行序生成可重复的 SQL 文本。``specs`` 里的建表 SQL 为 None 时跳过建表语句。"""
    lines = [f"-- {header}", f"-- source: {db_path.name}", f"-- generated by 脚本/db_dump.py", ""]
    if not db_path.is_file():
        lines.append(f"-- 库不存在，跳过：{db_path}")
        return "\n".join(lines) + "\n"

    conn = sqlite3.connect(f"file:{db_path.as_posix()}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        for table, ddl, order in specs:
            try:
                rows = conn.execute(f'SELECT * FROM "{table}" ORDER BY {order}').fetchall()
            except sqlite3.Error as exc:
                lines.append(f"-- 表 {table} 读取失败：{exc}")
                continue
            cols = [d[0] for d in conn.execute(f'SELECT * FROM "{table}" LIMIT 0').description]
            collist = ", ".join(f'"{c}"' for c in cols)
            lines.append(f"-- {table}: {len(rows)} 行")
            if ddl:
                lines.append(ddl)
            if rows:
                lines.append(f"DELETE FROM \"{table}\";")
            for r in rows:
                vals = ", ".join(_sql_literal(r[c]) for c in cols)
                lines.append(f'INSERT INTO "{table}" ({collist}) VALUES ({vals});')
            lines.append("")
    finally:
        conn.close()
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, text: str) -> tuple[bool, int]:
    """内容没变就不写 —— 幂等是 backup 脚本的基本礼貌（否则每天都多一个空 commit）。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old == text:
        return False, len(text.encode("utf-8"))
    path.write_text(text, encoding="utf-8", newline="\n")
    return True, len(text.encode("utf-8"))


def main() -> int:
    ap = argparse.ArgumentParser(description="dump 数据库为可 diff 的 SQL")
    ap.add_argument("--index", action="store_true", help="连索引库一起 dump（体积大，日常别开）")
    ap.add_argument("--check", action="store_true", help="只报差异不写文件")
    args = ap.parse_args()

    targets = ["versions"] + (["index"] if args.index else [])
    changed_any = False
    for key in targets:
        db_path, specs = TABLES[key]
        text = dump_db(db_path, specs, f"ai-memory {key} 数据库 dump")
        out = OUT_DIR / f"{key}.sql"
        if args.check:
            old = out.read_text(encoding="utf-8") if out.is_file() else ""
            same = old == text
            print(f"{out.name}: {'无变化' if same else '有变化'}（{len(text)} 字节）")
            changed_any = changed_any or not same
        else:
            changed, size = write_if_changed(out, text)
            print(f"{out.name}: {'已更新' if changed else '无变化'}（{size} 字节）")
            changed_any = changed_any or changed

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
